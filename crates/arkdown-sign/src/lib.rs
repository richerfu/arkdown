use std::path::{Path, PathBuf};
use std::process::Command;
use arkdown_core::SigningConfig;

#[derive(Debug, thiserror::Error)]
pub enum SignError {
    #[error("java not found in PATH. Install JRE to enable signing.")]
    JavaNotFound,
    #[error("hap-sign-tool.jar not found at '{0}'. Check your SDK installation.")]
    SignToolNotFound(PathBuf),
    #[error("Signing failed (exit code {code}): {stderr}")]
    SignFailed { code: i32, stderr: String },
    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),
}

pub struct HapSigner {
    /// Path to hap-sign-tool.jar. If None, tries to find in SDK.
    sign_tool_jar: Option<PathBuf>,
}

impl HapSigner {
    pub fn new(sign_tool_jar: Option<PathBuf>) -> Self {
        HapSigner { sign_tool_jar }
    }

    /// Sign an unsigned .hap or .hsp file in-place (output overwrites input if same path).
    pub fn sign(
        &self,
        unsigned: &Path,
        signed_output: &Path,
        config: &SigningConfig,
    ) -> Result<(), SignError> {
        // Find java
        if !java_in_path() {
            return Err(SignError::JavaNotFound);
        }

        // Find sign tool jar
        let jar = match &self.sign_tool_jar {
            Some(p) => p.clone(),
            None => find_sign_tool_jar()?,
        };
        if !jar.exists() {
            return Err(SignError::SignToolNotFound(jar));
        }

        // Resolve passwords: prefer env vars over config (which may be encrypted)
        let key_password = std::env::var("ARKDOWN_KEY_PASSWORD")
            .unwrap_or_else(|_| config.key_password.clone());
        let store_password = std::env::var("ARKDOWN_STORE_PASSWORD")
            .unwrap_or_else(|_| config.store_password.clone());

        let output = Command::new("java")
            .args([
                "-jar", &jar.to_string_lossy(),
                "sign-app",
                "-keyAlias", &config.key_alias,
                "-signAlg", &config.sign_alg,
                "-mode", "localSign",
                "-appCertFile", &config.cert_path.to_string_lossy(),
                "-profileFile", &config.profile_path.to_string_lossy(),
                "-inFile", &unsigned.to_string_lossy(),
                "-outFile", &signed_output.to_string_lossy(),
                "-keystoreFile", &config.store_file.to_string_lossy(),
                "-keystorePwd", &store_password,
                "-keyPwd", &key_password,
            ])
            .output()?;

        if !output.status.success() {
            return Err(SignError::SignFailed {
                code: output.status.code().unwrap_or(-1),
                stderr: String::from_utf8_lossy(&output.stderr).to_string(),
            });
        }
        Ok(())
    }

    /// If no signing config, produce unsigned output with a warning.
    pub fn sign_or_skip(
        &self,
        unsigned: &Path,
        signed_output: &Path,
        config: Option<&SigningConfig>,
    ) -> Result<(), SignError> {
        match config {
            None => {
                // No signing config: just copy the unsigned file to output path
                if unsigned != signed_output {
                    std::fs::copy(unsigned, signed_output)?;
                }
                eprintln!("warning: no signing config found — producing unsigned {}", signed_output.display());
                Ok(())
            }
            Some(cfg) => self.sign(unsigned, signed_output, cfg),
        }
    }
}

fn java_in_path() -> bool {
    Command::new("java")
        .arg("-version")
        .output()
        .map(|o| o.status.success() || String::from_utf8_lossy(&o.stderr).contains("version"))
        .unwrap_or(false)
}

fn find_sign_tool_jar() -> Result<PathBuf, SignError> {
    // Look in common SDK locations
    let candidates = [
        "tools/lib/hap-sign-tool.jar",
        "../tools/lib/hap-sign-tool.jar",
    ];
    // Check OHOS_SDK_HOME
    if let Ok(sdk) = std::env::var("OHOS_SDK_HOME") {
        let jar = PathBuf::from(&sdk)
            .join("default/openharmony/toolchains/lib/hap-sign-tool.jar");
        if jar.exists() { return Ok(jar); }
    }
    // Check relative paths
    for c in &candidates {
        let p = PathBuf::from(c);
        if p.exists() { return Ok(p); }
    }
    Err(SignError::SignToolNotFound(PathBuf::from("hap-sign-tool.jar")))
}

/// The hvigorw compatibility shell script template.
pub const HVIGORW_SCRIPT: &str = r#"#!/bin/bash
# hvigorw — drop-in replacement using arkdown
# Generated by: arkdown init --compat

ARKDOWN_BIN="${ARKDOWN_HOME:-$(which arkdown 2>/dev/null)}"
if [ -z "$ARKDOWN_BIN" ]; then
    echo "ERROR: arkdown not found. Install arkdown or set ARKDOWN_HOME." >&2
    exit 2
fi

CMD="${1:-default}"; shift 2>/dev/null || true
ARGS=()
MODE="debug"
MODULE=""
PRODUCT=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --mode)    MODE="$2";    shift 2 ;;
        -m)        MODULE="$2";  shift 2 ;;
        --product) PRODUCT="$2"; shift 2 ;;
        -p)        ARGS+=("-p" "$2"); shift 2 ;;
        *)         ARGS+=("$1"); shift ;;
    esac
done

TARGET_ARGS=()
[[ -n "$MODULE" ]]  && TARGET_ARGS+=("--module"  "$MODULE")
[[ -n "$PRODUCT" ]] && TARGET_ARGS+=("--product" "$PRODUCT")

case "$CMD" in
    assembleHap)  exec "$ARKDOWN_BIN" build --target hap --mode "$MODE" "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    assembleHsp)  exec "$ARKDOWN_BIN" build --target hsp --mode "$MODE" "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    assembleHar)  exec "$ARKDOWN_BIN" build --target har --mode "$MODE" "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    assembleApp)  exec "$ARKDOWN_BIN" build --target app --mode "$MODE" "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    clean)        exec "$ARKDOWN_BIN" clean "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    test)         exec "$ARKDOWN_BIN" test  "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    default|"")   exec "$ARKDOWN_BIN" build "${TARGET_ARGS[@]}" "${ARGS[@]}" ;;
    *)
        echo "ERROR: Unknown hvigorw command: $CMD" >&2
        echo "Supported: assembleHap, assembleHsp, assembleHar, assembleApp, clean, test" >&2
        exit 2
        ;;
esac
"#;

/// Write the hvigorw compatibility script to the project root.
pub fn write_hvigorw_script(project_root: &Path) -> std::io::Result<()> {
    let script_path = project_root.join("hvigorw");
    std::fs::write(&script_path, HVIGORW_SCRIPT)?;

    // Make executable on Unix
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&script_path)?.permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(&script_path, perms)?;
    }

    println!("Written: {}", script_path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_sign_or_skip_no_config_copies() {
        let tmp = tempfile::tempdir().unwrap();
        let src = tmp.path().join("unsigned.hap");
        let dst = tmp.path().join("signed.hap");
        std::fs::write(&src, b"fake-hap-content").unwrap();

        let signer = HapSigner::new(None);
        let result = signer.sign_or_skip(&src, &dst, None);
        assert!(result.is_ok());
        assert!(dst.exists());
        assert_eq!(std::fs::read(&dst).unwrap(), b"fake-hap-content");
    }

    #[test]
    fn test_sign_or_skip_same_path_no_copy() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("unsigned.hap");
        std::fs::write(&path, b"fake").unwrap();

        let signer = HapSigner::new(None);
        let result = signer.sign_or_skip(&path, &path, None);
        assert!(result.is_ok());
    }

    #[test]
    fn test_write_hvigorw_script() {
        let tmp = tempfile::tempdir().unwrap();
        write_hvigorw_script(tmp.path()).unwrap();
        let script = tmp.path().join("hvigorw");
        assert!(script.exists());
        let content = std::fs::read_to_string(&script).unwrap();
        assert!(content.contains("assembleHap"));
        assert!(content.contains("arkdown"));
    }

    #[test]
    fn test_hvigorw_script_contains_all_commands() {
        assert!(HVIGORW_SCRIPT.contains("assembleHsp"));
        assert!(HVIGORW_SCRIPT.contains("assembleHar"));
        assert!(HVIGORW_SCRIPT.contains("assembleApp"));
        assert!(HVIGORW_SCRIPT.contains("clean"));
        assert!(HVIGORW_SCRIPT.contains("--mode"));
    }
}
