#[cfg(test)]
mod tests {
    use super::*;

    // ── Error cases ─────────────────────────────────────────────────────

    #[test]
    fn test_empty_bytes_returns_err() {
        let result = SigningKey::from_pkcs12(&[], "", "key", "password");
        assert!(result.is_err(), "empty bytes must return Err, not panic");
    }

    #[test]
    fn test_random_bytes_returns_err() {
        let junk = b"this is definitely not a valid PKCS#12 file!";
        let result = SigningKey::from_pkcs12(junk, "pass", "key", "pass");
        assert!(result.is_err(), "random bytes must return Err");
    }

    #[test]
    fn test_wrong_password_returns_err() {
        // Load the test P12 but supply the wrong key password.
        // If the fixture is absent the test is skipped gracefully.
        let p12_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures/test.p12");
        if !p12_path.exists() {
            eprintln!("SKIP: test P12 fixture not found at {:?}", p12_path);
            return;
        }
        let p12_bytes = std::fs::read(&p12_path).expect("read test.p12");
        let result = SigningKey::from_pkcs12(&p12_bytes, "wrong", "key", "wrong_password");
        assert!(result.is_err(), "wrong password must return Err");
    }

    /// Load the generated test PKCS#12 fixture (password: `test123`).
    ///
    /// This test requires the fixture file at
    /// `crates/arkdown-sign/tests/fixtures/test.p12`, generated by:
    /// ```bash
    /// openssl req -x509 -newkey rsa:2048 -keyout /tmp/key.pem -out /tmp/cert.pem \
    ///     -days 3650 -nodes -subj '/CN=test'
    /// openssl pkcs12 -export -out crates/arkdown-sign/tests/fixtures/test.p12 \
    ///     -inkey /tmp/key.pem -in /tmp/cert.pem -passout pass:test123
    /// ```
    #[test]
    fn test_load_rsa_p12_fixture() {
        let p12_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures/test.p12");
        if !p12_path.exists() {
            eprintln!("SKIP: test P12 fixture not found at {:?}", p12_path);
            return;
        }
        let p12_bytes = std::fs::read(&p12_path).expect("read test.p12");
        let result = SigningKey::from_pkcs12(&p12_bytes, "test123", "1", "test123");
        assert!(
            result.is_ok(),
            "loading valid RSA P12 with correct password must succeed: {:?}",
            result.err()
        );
        let key = result.unwrap();
        assert!(!key.private_key_der.is_empty(), "private key DER must not be empty");
        assert!(!key.cert_chain.is_empty(), "certificate chain must not be empty");
        assert!(
            !key.cert_chain[0].is_empty(),
            "leaf certificate DER must not be empty"
        );
    }

    // ── from_pem: base64 decoder ─────────────────────────────────────────

    /// Test that `from_pem` with invalid base64 returns Err without panicking.
    #[test]
    fn test_from_pem_invalid_base64_returns_err() {
        let bad_key = "-----BEGIN PRIVATE KEY-----\n!!!not base64!!!\n-----END PRIVATE KEY-----";
        let bad_cert = "-----BEGIN CERTIFICATE-----\n!!!not base64!!!\n-----END CERTIFICATE-----";
        let result = SigningKey::from_pem(bad_key, bad_cert);
        assert!(result.is_err(), "invalid PEM base64 must return Err");
    }

    /// Test that empty PEM blocks return Err (no DER bytes to parse).
    #[test]
    fn test_from_pem_empty_content_returns_err_or_ok_with_empty_key() {
        let empty_key = "-----BEGIN PRIVATE KEY-----\n-----END PRIVATE KEY-----";
        let empty_cert = "-----BEGIN CERTIFICATE-----\n-----END CERTIFICATE-----";
        // Empty PEM may produce Ok(SigningKey { private_key_der: [], cert_chain: [vec![]] })
        // or Err — both are acceptable as long as there is no panic.
        let result = SigningKey::from_pem(empty_key, empty_cert);
        let _ = result; // no panic is the requirement
    }

    /// Verify the base64 decoder handles padding correctly.
    #[test]
    fn test_base64_decode_known_vector() {
        // "hello" → aGVsbG8=
        let encoded = "aGVsbG8=";
        let pem = format!(
            "-----BEGIN PRIVATE KEY-----\n{encoded}\n-----END PRIVATE KEY-----"
        );
        // from_pem does pure base64 decode of key pem (we can't parse it as PKCS#8,
        // but we can verify the decode succeeded by checking that from_pem returns
        // PemError at the PKCS#8 parse step, not at the base64 decode step).
        let cert_pem = "-----BEGIN CERTIFICATE-----\naGVsbG8=\n-----END CERTIFICATE-----";
        let result = SigningKey::from_pem(&pem, cert_pem);
        // Result will be Err(PemError) because "hello" is not valid PKCS#8,
        // but it must NOT be an Err from base64 decode.
        match &result {
            Err(crate::error::SignError::PemError(msg)) => {
                assert!(
                    !msg.contains("base64 decode"),
                    "base64 decode of 'aGVsbG8=' must succeed; got PemError: {msg}"
                );
            }
            _ => {} // Ok or other errors are acceptable
        }
    }
}

/// Minimal base64 decoder (standard alphabet).
fn base64_decode(input: &str) -> Result<Vec<u8>, String> {
    const TABLE: &[u8; 64] =
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

    let mut lookup = [0xFFu8; 256];
    for (i, &c) in TABLE.iter().enumerate() {
        lookup[c as usize] = i as u8;
    }

    let bytes: Vec<u8> = input
        .bytes()
        .filter(|&b| b != b'\n' && b != b'\r' && b != b' ')
        .collect();

    let mut output = Vec::with_capacity((bytes.len() * 3) / 4);
    let mut i = 0;
    while i < bytes.len() {
        let b0 = bytes.get(i).copied().unwrap_or(b'=');
        let b1 = bytes.get(i + 1).copied().unwrap_or(b'=');
        let b2 = bytes.get(i + 2).copied().unwrap_or(b'=');
        let b3 = bytes.get(i + 3).copied().unwrap_or(b'=');

        let v0 = if b0 == b'=' { 0u8 } else { lookup[b0 as usize] };
        let v1 = if b1 == b'=' { 0u8 } else { lookup[b1 as usize] };
        let v2 = if b2 == b'=' { 0u8 } else { lookup[b2 as usize] };
        let v3 = if b3 == b'=' { 0u8 } else { lookup[b3 as usize] };

        if v0 == 0xFF || v1 == 0xFF {
            return Err(format!("invalid base64 char at position {i}"));
        }

        output.push((v0 << 2) | (v1 >> 4));
        if b2 != b'=' {
            if v2 == 0xFF {
                return Err(format!("invalid base64 char at position {}", i + 2));
            }
            output.push((v1 << 4) | (v2 >> 2));
        }
        if b3 != b'=' {
            if v3 == 0xFF {
                return Err(format!("invalid base64 char at position {}", i + 3));
            }
            output.push((v2 << 6) | v3);
        }
        i += 4;
    }
    Ok(output)
}
