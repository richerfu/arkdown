use arkdown_core::ModuleSource;

use crate::error::EtsTransformError;

/// Transform an ArkTS `.ets` source file into TypeScript.
///
/// Steps:
/// 1. Run the etsChecker (diagnostics only — does not abort on warnings)
/// 2. Apply a text-based structural transform: struct → class, strip bare decorators
/// 3. Return the transformed TypeScript source string
///
/// Full AST-based desugaring of the `build()` DSL body is deferred to v2
/// (SPEC-004a). The v1 implementation is sufficient for the downstream
/// TypeScript parse and module-graph analysis phases.
pub fn transform_ets(source: &ModuleSource) -> Result<String, EtsTransformError> {
    let content = &source.content;

    // Fast path: files with no ArkUI-specific syntax pass through unchanged.
    // The module_type change from Ets → Ts still happens in the plugin.
    if !content.contains("@Component") && !content.contains("@Entry") {
        return Ok(content.clone());
    }

    // Run checker diagnostics (non-fatal).
    let diagnostics = crate::checker::check(content, &source.id.id);
    for diag in &diagnostics {
        eprintln!("[ets-checker] {:?}", diag);
    }

    // Apply text-based structural transform.
    Ok(strip_arkts_struct_syntax(content))
}

/// Strip ArkTS struct-based component syntax that TypeScript cannot parse.
///
/// This is a best-effort text pass. It handles the common patterns:
///
/// ```text
/// @Entry
/// @Component
/// struct Foo { ... }
/// ```
///
/// → replaced with `class Foo extends ViewPU { ... }` so that downstream TS
/// processing can continue. Full component desugaring (backing fields, constructor,
/// `initialRenderFunction`, etc.) is generated by `component::generate_view_pu_class`
/// in the v2 full-AST pass.
///
/// The text pass is intentionally conservative — it only rewrites the struct
/// header lines and strips bare decorator-only lines (`@Entry`, `@Preview`).
fn strip_arkts_struct_syntax(source: &str) -> String {
    // Normalize line endings.
    let source = source.replace("\r\n", "\n");

    // Replace @Entry + @Component + struct header (multi-line patterns).
    let result = source
        .replace("@Entry\n@Component\nstruct ", "@__ENTRY__@__COMPONENT__ class ")
        .replace("@Component\nstruct ", "@__COMPONENT__ class ")
        // Handle cases where @Entry appears on a separate line before @Component
        .replace("@Entry\n@Component\r\nstruct ", "@__ENTRY__@__COMPONENT__ class ");

    // Process line by line to strip the marker pseudo-decorators and bare decorators.
    let mut lines_out: Vec<String> = Vec::with_capacity(result.lines().count());
    for line in result.lines() {
        let trimmed = line.trim();
        // Skip bare @Entry / @Preview lines (consumed by earlier replacement
        // or standalone occurrences that TS won't accept).
        if trimmed == "@Entry" || trimmed == "@Preview" {
            continue;
        }
        // Rewrite the combined pseudo-decorator class lines.
        if trimmed.starts_with("@__ENTRY__@__COMPONENT__ class ") {
            let class_part =
                trimmed.trim_start_matches("@__ENTRY__@__COMPONENT__ class ");
            // Strip the trailing `{` (which may have a space before it) to extract
            // just the class name, then reassemble with `extends ViewPU {`.
            let class_name = class_part.trim_end_matches('{').trim();
            lines_out.push(format!("class {} extends ViewPU {{", class_name));
            continue;
        }
        if trimmed.starts_with("@__COMPONENT__ class ") {
            let class_part = trimmed.trim_start_matches("@__COMPONENT__ class ");
            let class_name = class_part.trim_end_matches('{').trim();
            lines_out.push(format!("class {} extends ViewPU {{", class_name));
            continue;
        }
        lines_out.push(line.to_string());
    }

    lines_out.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use arkdown_core::{ModuleType, ResolvedId};

    fn make_source(content: &str) -> ModuleSource {
        ModuleSource {
            id: ResolvedId {
                id: "test.ets".to_string(),
                external: false,
                module_type: ModuleType::Ets,
                ..Default::default()
            },
            content: content.to_string(),
            source_map: None,
        }
    }

    #[test]
    fn test_non_component_passthrough() {
        let src = "import { something } from '@ohos/hilog';\nconst x = 1;";
        let result = transform_ets(&make_source(src)).unwrap();
        assert_eq!(result, src);
    }

    #[test]
    fn test_strip_component_struct() {
        let src = "@Component\nstruct MyView {\n  build() {}\n}";
        let result = transform_ets(&make_source(src)).unwrap();
        assert!(result.contains("class MyView extends ViewPU"));
        assert!(!result.contains("struct MyView"));
    }

    #[test]
    fn test_strip_entry_component_struct() {
        let src = "@Entry\n@Component\nstruct Page {\n  build() {}\n}";
        let result = transform_ets(&make_source(src)).unwrap();
        assert!(result.contains("class Page extends ViewPU"));
        assert!(!result.contains("@Entry"));
        assert!(!result.contains("struct Page"));
    }
}
